// Work out, for every book, how printed page numbers map to PDF pages, by reading the running
// page numbers in each page's first and last lines. Books with inserted plates or unnumbered
// pages get several segments. Writes bibliography/page-offsets.yaml (numbers only, no book text).
//
//   node tools/corpus/offsets.mjs

import { readFileSync, readdirSync, writeFileSync, existsSync } from 'node:fs';
import { join } from 'node:path';
import { stringify } from 'yaml';
import { loadWorks, CORPUS, ROOT } from '../lib/works.mjs';

const MIN_SEGMENT = 5;

function candidates(text, pdfPage) {
  const lines = text.split('\n').map((l) => l.trim()).filter(Boolean);
  const edge = [...lines.slice(0, 3), ...lines.slice(-3)];
  const out = new Set();
  for (const line of edge) {
    // OCR sometimes splits a page number ("1 18" for 118), so also try the digits joined.
    const ms = [/^(\d{1,4})\b/, /\b(\d{1,4})$/, /^(\d{1,2} \d{1,3})\b/, /\b(\d{1,2} \d{1,3})$/].map((re) => re.exec(line));
    for (const m of ms) {
      if (!m) continue;
      const printed = Number(m[1].replace(' ', ''));
      if (printed >= 1 && printed <= pdfPage) out.add(pdfPage - printed);
    }
  }
  return out;
}

// Fit a piecewise-constant offset to the whole book with dynamic programming: each page costs 1 if
// it shows page numbers that disagree with the chosen offset (0 if it shows none, e.g. a chapter
// opener), and each change of offset costs SWITCH. A NONE state absorbs front matter and noise.
const SWITCH = 6;
const NONE_COST = 0.6;

export function computeSegments(pages) {
  const n = pages.length;
  const cands = pages.map((t, i) => candidates(t, i + 1));
  const freq = new Map();
  for (const c of cands) for (const o of c) freq.set(o, (freq.get(o) || 0) + 1);
  const domain = [null, ...[...freq].filter(([, k]) => k >= MIN_SEGMENT).map(([o]) => o)];
  const K = domain.length;
  const cost = (i, k) => (domain[k] === null ? (cands[i].size ? NONE_COST : 0) : cands[i].size && !cands[i].has(domain[k]) ? 1 : 0);

  const back = Array.from({ length: n }, () => new Int32Array(K));
  let prev = Float64Array.from({ length: K }, (_, k) => cost(0, k));
  for (let i = 1; i < n; i++) {
    let bestK = 0;
    for (let k = 1; k < K; k++) if (prev[k] < prev[bestK]) bestK = k;
    const cur = new Float64Array(K);
    for (let k = 0; k < K; k++) {
      const stay = prev[k];
      const jump = prev[bestK] + SWITCH;
      back[i][k] = stay <= jump ? k : bestK;
      cur[k] = Math.min(stay, jump) + cost(i, k);
    }
    prev = cur;
  }
  let k = 0;
  for (let j = 1; j < K; j++) if (prev[j] < prev[k]) k = j;
  const path = new Array(n);
  for (let i = n - 1; i >= 0; i--) {
    path[i] = domain[k];
    k = back[i][k];
  }

  const segments = [];
  for (let i = 0; i < n; i++) {
    if (path[i] === null) continue;
    const last = segments.at(-1);
    if (last && last.offset === path[i] && last.to === i) last.to = i + 1;
    else segments.push({ from: i + 1, to: i + 1, offset: path[i] });
  }
  return segments.filter((s) => s.to - s.from + 1 >= MIN_SEGMENT);
}

// printed page -> pdf page using segments; null if the page falls outside every segment.
export function printedToPdf(segments, printed) {
  for (const s of segments) {
    const pdf = printed + s.offset;
    if (pdf >= s.from && pdf <= s.to) return pdf;
  }
  // Allow a page just past a segment end (e.g. a last page without a running number).
  for (const s of segments) {
    const pdf = printed + s.offset;
    if (pdf > s.to && pdf <= s.to + 2) return pdf;
  }
  return null;
}

export function readPages(id) {
  const dir = join(CORPUS, id);
  if (!existsSync(dir)) return null;
  return readdirSync(dir)
    .filter((f) => /^p\d{4}\.txt$/.test(f))
    .sort()
    .map((f) => readFileSync(join(dir, f), 'utf8'));
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const out = {};
  for (const w of loadWorks()) {
    const pages = readPages(w.id);
    if (!pages) {
      console.warn(`${w.id}: no corpus yet, skipped`);
      continue;
    }
    const segs = computeSegments(pages);
    out[w.id] = segs;
    const covered = segs.reduce((a, s) => a + s.to - s.from + 1, 0);
    console.log(`${w.id.padEnd(26)} ${segs.length} segment(s), ${covered}/${pages.length} pages: ${segs.map((s) => `pdf ${s.from}-${s.to} = printed ${s.from - s.offset}-${s.to - s.offset}`).join(' | ')}`);
  }
  writeFileSync(
    join(ROOT, 'bibliography', 'page-offsets.yaml'),
    '# Generated by tools/corpus/offsets.mjs: printed page = pdf page - offset within each segment.\n' + stringify(out),
  );
}
